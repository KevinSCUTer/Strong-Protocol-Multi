#!/usr/bin/env node
// tools/import-tutorial.mjs — import the generated illustrated-guides package (self-contained
// single-file HTML with the game art embedded as base64) into public/tutorial/ as deployable pages.
//
// The guide generator (the upstream checkout's communicate/build.mjs) embeds every image as a
// `data:image/png;base64,…` URI: bond icons byte-exact from public/assets/bond/, everything else
// (char avatars) as a 96 px `sips -Z 96` thumbnail of the asset. This tool replaces every embedded
// image with the URL of the identical file in the local shared asset folder (public/assets — the
// machine's game-asset checkout, gitignored), matched by SHA-256 of the decoded bytes:
//   1. exact match against the asset files themselves (the bond icons);
//   2. otherwise against regenerated 96 px thumbnails of /assets/char/avatar/ (the same sips call
//      the generator makes — deterministic, byte-exact); the page then links the full-size original.
// No game art is ever written into git (AGENTS.md): the pages only reference /assets/… URLs that
// this game server serves from the local asset folder. A payload with no match is replaced by a
// small caption span carrying the image's alt text — never by embedded data (the tool reports it).
//
// The landing page (index.html) additionally gets the fork note: the guides describe the official
// 4-player reference, this deployment is the capacity fork (rooms up to 20, fixed card-pool groups
// drafting in parallel). The note is a small inline script shown in the reader's game language
// (localStorage sp.pref.lang, else the browser languages).
//
// Usage: node tools/import-tutorial.mjs [sourceDir]
//   sourceDir   the generated package (default: ../Kevin/Tutorial beside this repository checkout;
//               the files are the output of the guide generator's communicate/build.mjs)

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync, realpathSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, extname } from 'node:path';
import os from 'node:os';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'public');
const DEST = join(PUBLIC, 'tutorial');
const SOURCE_DIR = process.argv[2]
  || [join(ROOT, '..', '..', 'Kevin', 'Tutorial'), join(ROOT, '..', 'Kevin', 'Tutorial')].find((p) => existsSync(p))
  || join(ROOT, '..', '..', 'Kevin', 'Tutorial');
const PAGES = ['index.html', 'stronghold_eli5.html', 'how_to_play_with_teammate.html', 'lol.html', 'arknight_stronghold.html'];

if (!existsSync(SOURCE_DIR)) {
  console.error(`import-tutorial: source package not found: ${SOURCE_DIR}`);
  console.error('usage: node tools/import-tutorial.mjs [sourceDir]  (the generated single-file guide package)');
  process.exit(1);
}
// public/assets is a symlink to the machine's shared game-asset checkout (gitignored, AGENTS.md).
const ASSETS = realpathSync(join(PUBLIC, 'assets'));

// --------------------------------------------------------------------------------------------------
// SHA-256 index of the local assets (raw files first, then regenerated 96 px thumbnails)
// --------------------------------------------------------------------------------------------------

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/** Every image file below dir as [absPath, relPath]. */
function walk(dir, prefix = '') {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(join(dir, e.name), rel));
    else if (['.png', '.jpg', '.jpeg', '.webp'].includes(extname(e.name).toLowerCase())) out.push([join(dir, e.name), rel]);
  }
  return out;
}

const rawBySha = new Map(); // sha → asset rel path (first file wins)
let rawDupes = 0;
for (const [abs, rel] of walk(ASSETS)) {
  const k = sha256(readFileSync(abs));
  if (rawBySha.has(k)) rawDupes++;
  else rawBySha.set(k, rel);
}

// Thumbnails: the generator embeds `sips -Z 96` rescales of char/avatar files (everything but
// bond/ is rescaled by its resolve(); only char/avatar is used by its templates). sips is
// deterministic here — the regenerated bytes match the embedded ones (verified). The cache lives in
// the OS temp dir keyed by the asset's mtime, so repeated imports are fast and stale thumbs never match.
const THUMB_SOURCE_DIRS = ['char/avatar'];
const thumbCache = join(os.tmpdir(), 'sp-tutorial-thumbs');
mkdirSync(thumbCache, { recursive: true });
const thumbBySha = new Map(); // sha → { rel, abs }
let thumbsMade = 0;
for (const dir of THUMB_SOURCE_DIRS) {
  const absDir = join(ASSETS, dir);
  if (!existsSync(absDir)) continue;
  for (const [abs, rel] of walk(absDir)) {
    const cached = join(thumbCache, rel.replaceAll('/', '_'));
    const mtime = statSync(abs).mtimeMs;
    if (!existsSync(cached) || statSync(cached).mtimeMs < mtime) {
      try {
        execFileSync('/usr/bin/sips', ['-Z', '96', abs, '--out', cached], { stdio: 'pipe' });
        thumbsMade++;
      } catch { continue; } // no sips (non-macOS): thumbnail matching is unavailable, raw matching still works
    }
    const k = sha256(readFileSync(cached));
    if (!thumbBySha.has(k)) thumbBySha.set(k, `${dir}/${rel}`);
  }
}

/** Resolve one embedded payload → `/assets/<rel>` or null. */
function resolveImage(bytes) {
  const rel = rawBySha.get(sha256(bytes));
  if (rel) return { url: `/assets/${rel}`, how: 'exact' };
  const thumb = thumbBySha.get(sha256(bytes));
  if (thumb) return { url: `/assets/${thumb}`, how: 'thumbnail' };
  return null;
}

