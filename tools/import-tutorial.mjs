// --------------------------------------------------------------------------------------------------
// Conversion
// --------------------------------------------------------------------------------------------------

const IMG_RE = /<img\b[^>]*\bsrc="data:image\/(png|jpeg|webp);base64,([A-Za-z0-9+/=]+)"[^>]*>/g;
const ALT_RE = /\balt="([^"]*)"/;

mkdirSync(DEST, { recursive: true });
let totalAll = 0, exactAll = 0, thumbAll = 0, missingAll = 0;

for (const name of PAGES) {
  const srcPath = join(SOURCE_DIR, name);
  if (!existsSync(srcPath)) { console.error(`import-tutorial: missing page in source package: ${name}`); process.exit(1); }
  const src = readFileSync(srcPath);
  const html = src.toString('utf8');

  const counts = { exact: 0, thumbnail: 0, missing: 0 };
  const converted = html.replace(IMG_RE, (tag, _type, b64) => {
    const hit = resolveImage(Buffer.from(b64, 'base64'));
    if (hit) { counts[hit.how]++; return tag.replace(/src="data:image\/[^;]+;base64,[^"]+"/, `src="${hit.url}"`); }
    counts.missing++;
    // No matching local asset: keep the meaning (alt text) as a caption — never embed the bytes.
    const alt = ALT_RE.exec(tag)?.[1] || '';
    return `<span class="sp-img-missing" role="img" aria-label="${alt}">${alt}</span>`;
  });

  // Images now load from the site's assets; remove the source package's single-file/offline claims.
  const out = name === 'index.html' ? converted
    .replace('<span>图片全内嵌</span>', '<span>图片随站点加载</span>')
    .replace('<span>断网可看</span>', '<span>在线阅读</span>') : converted;
  const sourceLabel = `Tutorial/${name}`;
  const provenance = `<!--
  Converted by tools/import-tutorial.mjs from ${sourceLabel} (source sha256 ${sha256(src).slice(0, 16)}…).
  ${counts.exact + counts.thumbnail + counts.missing} embedded game images replaced by /assets/… URLs (SHA-256 match:
  ${counts.exact} byte-exact, ${counts.thumbnail} via the generator's 96 px thumbnail${counts.missing ? `, ${counts.missing} omitted as captions` : ''}).
  No game art is committed (AGENTS.md); the images load from this server's local asset folder.
  Regenerate: node tools/import-tutorial.mjs <sourceDir>
-->`;
  // the provenance comment goes after the doctype (anything before it can trigger quirks mode)
  const body = /^<!doctype html>/i.test(out) ? out.replace(/^(<!doctype html>)/i, `$1\n${provenance}`) : `${provenance}\n${out}`;
  const withNote = name === 'index.html' ? body.replace(/<\/body>/i, `${FORK_NOTE}\n</body>`) : body;
  writeFileSync(join(DEST, name), withNote);
  totalAll += counts.exact + counts.thumbnail + counts.missing;
  exactAll += counts.exact;
  thumbAll += counts.thumbnail;
  missingAll += counts.missing;
  console.log(`${name}: ${counts.exact + counts.thumbnail + counts.missing} images (${counts.exact} exact, ${counts.thumbnail} thumbnail${counts.missing ? `, ${counts.missing} MISSING` : ''})`);
}

console.log(`import-tutorial: ${totalAll} images → public/tutorial/ (${exactAll} exact, ${thumbAll} via 96 px thumbnail; ${thumbsMade} thumbnails regenerated; ${rawDupes} duplicate asset bytes indexed once)`);
if (missingAll) {
  console.warn(`import-tutorial: ${missingAll} images had no matching local asset and were left out as captions —`);
  console.warn('  update the local asset folder (npm run setup / tools/fetch-assets.mjs) and re-run this tool.');
}
