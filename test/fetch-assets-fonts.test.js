// test/fetch-assets-fonts.test.js — fonts in tools/fetch-assets.mjs --add-only (DEV-20261010-05): a fresh clone
// sharing public/fonts (or without it at all) used to get NO fonts at all, because --add-only skipped the font
// step entirely. It now adds only what is missing — an original, a .woff2, fonts.css — and never rewrites,
// re-encodes or re-checks an existing shared file. --download-only (the deployment's manifest gate) is covered in
// test/deploy.test.js; here are the font jobs, buildFonts in both modes, and the add-only downloader.
// Run: node --test test/fetch-assets-fonts.test.js

import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildFonts, FONTS, fontJobs } from '../tools/assets/fonts.mjs';
import { Downloader } from '../tools/assets/downloader.mjs';
import { parseArgs, runExitCode } from '../tools/fetch-assets.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const quiet = () => {};

/** A minimal parseable sfnt: flavor 0x00010000, one known table ('name'), in-bounds offset and length. */
function sfnt() {
  const buf = Buffer.alloc(12 + 16 + 8);
  buf.writeUInt32BE(0x00010000, 0);
  buf.writeUInt16BE(1, 4);
  buf.write('name', 12, 'latin1');
  buf.writeUInt32BE(28, 20); // table offset
  buf.writeUInt32BE(8, 24);  // table length
  return buf;
}

test('fontJobs: the three self-hosted fonts, from the font repo, kind font (bytes from research 07)', () => {
  const jobs = fontJobs();
  assert.equal(jobs.length, FONTS.length);
  for (const [i, job] of jobs.entries()) {
    assert.equal(job.rel, `${FONTS[i].name}.${FONTS[i].ext}`);
    assert.equal(job.kind, 'font');
    assert.match(job.urls[0], /The-font-of-Arknights/);
  }
});

test('buildFonts (plain): a fresh fonts dir gets .woff2 conversions and fonts.css', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-fresh-'));
  try {
    for (const f of FONTS) fs.writeFileSync(path.join(dir, `${f.name}.${f.ext}`), sfnt());
    const r = await buildFonts(dir, quiet);
    assert.deepEqual(r.errors, []);
    for (const f of FONTS) {
      const woff2 = fs.readFileSync(path.join(dir, `${f.name}.woff2`));
      assert.equal(woff2.readUInt32BE(0), 0x774f4632, `${f.name}.woff2`);
      assert.equal(r.files[f.name].woff2, `/fonts/${f.name}.woff2`);
    }
    assert.match(fs.readFileSync(path.join(dir, 'fonts.css'), 'utf8'), /@font-face/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('buildFonts --add-only: missing .woff2 / fonts.css are added; existing ones are never modified — not even re-checked', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-add-'));
  try {
    for (const f of FONTS) fs.writeFileSync(path.join(dir, `${f.name}.${f.ext}`), sfnt());
    // bender-regular keeps a hand-placed .woff2 that does not match its source at all: add-only leaves it as it is.
    const foreign = Buffer.from('wOF2-foreign-content-not-ours');
    fs.writeFileSync(path.join(dir, 'bender-regular.woff2'), foreign);
    fs.writeFileSync(path.join(dir, 'fonts.css'), '/* shared, not ours */');
    const r = await buildFonts(dir, quiet, { addOnly: true });
    assert.deepEqual(r.errors, []);
    assert.deepEqual(fs.readFileSync(path.join(dir, 'bender-regular.woff2')), foreign, 'an existing shared .woff2 is byte-for-byte untouched');
    assert.match(fs.readFileSync(path.join(dir, 'fonts.css'), 'utf8'), /shared, not ours/, 'an existing fonts.css is not rewritten');
    for (const f of FONTS.slice(1)) {
      assert.equal(fs.readFileSync(path.join(dir, `${f.name}.woff2`)).readUInt32BE(0), 0x774f4632, `${f.name}.woff2 was generated`);
    }
    // the same without --add-only heals the foreign .woff2 (it decodes against the source and is re-encoded)
    const healed = await buildFonts(dir, quiet);
    assert.deepEqual(healed.errors, []);
    assert.notDeepEqual(fs.readFileSync(path.join(dir, 'bender-regular.woff2')), foreign);
    assert.match(fs.readFileSync(path.join(dir, 'fonts.css'), 'utf8'), /Generated by tools\/fetch-assets\.mjs/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('buildFonts --add-only on an empty dir: the fonts step reports the missing originals (the downloader fetches them first)', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-none-'));
  try {
    const r = await buildFonts(dir, quiet, { addOnly: true });
    assert.equal(r.errors.length, FONTS.length);
    assert.match(r.errors[0], /missing font /);
    assert.deepEqual(Object.keys(r.files), []);
    assert.equal(fs.existsSync(path.join(dir, 'fonts.css')), false, 'nothing to describe: no css');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('the add-only font downloader keeps every existing font file and fetches only the missing ones', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-dl-'));
  try {
    const existing = sfnt();
    fs.writeFileSync(path.join(dir, 'bender-regular.otf'), existing);
    const fetched = [];
    const dl = new Downloader({ root: dir, ledgerPath: path.join(dir, 'ledger.json'), keepExisting: true, force: true, retries: 1, backoffMs: 0, log: quiet,
      fetchImpl: async (url) => { fetched.push(url); return new Response(sfnt()); } });
    assert.equal(dl.force, false, '--force never applies in add-only');
    const results = await dl.run(fontJobs(), 'fonts');
    assert.equal(results.get('bender-regular.otf').status, 'skip', 'existing shared font, wrong ledger or not');
    assert.deepEqual(fs.readFileSync(path.join(dir, 'bender-regular.otf')), existing);
    assert.equal(fetched.length, FONTS.length - 1, 'only the missing two are fetched');
    for (const f of FONTS.slice(1)) assert.equal(results.get(`${f.name}.${f.ext}`).status, 'ok');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('a fresh clone whose font download failed is a failed deployment, not a success: the fonts gate (deploy) sees every file', async () => {
  // fontsStatus is the deployment gate's font check; one missing .woff2 is enough to fail it.
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-gate-'));
  try {
    const { encodeWoff2 } = await import('../tools/assets/woff2.mjs');
    const valid = encodeWoff2(sfnt());
    for (const f of FONTS) {
      fs.writeFileSync(path.join(dir, `${f.name}.${f.ext}`), sfnt());
      fs.writeFileSync(path.join(dir, `${f.name}.woff2`), valid);
    }
    fs.writeFileSync(path.join(dir, 'fonts.css'), '@font-face{}');
    const { fontsStatus } = await import('../tools/deploy.mjs');
    assert.equal(fontsStatus(dir).ok, true);
    fs.rmSync(path.join(dir, 'novecento-wide-normal.woff2'));
    const r = fontsStatus(dir);
    assert.deepEqual(r.missing, ['novecento-wide-normal.woff2']);
    assert.equal(r.ok, false);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('an interrupted run\'s zero-byte outputs count as missing: add-only regenerates them instead of preserving them forever', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-fonts-empty-'));
  try {
    for (const f of FONTS) fs.writeFileSync(path.join(dir, `${f.name}.${f.ext}`), sfnt());
    fs.writeFileSync(path.join(dir, 'novecento-wide-normal.woff2'), '');   // killed mid-write
    fs.writeFileSync(path.join(dir, 'fonts.css'), '');                     // ditto
    const r = await buildFonts(dir, quiet, { addOnly: true });
    assert.deepEqual(r.errors, [], 'an empty output is not a font error');
    const woff2 = fs.readFileSync(path.join(dir, 'novecento-wide-normal.woff2'));
    assert.equal(woff2.readUInt32BE(0), 0x774f4632, 'the empty .woff2 was regenerated');
    assert.match(fs.readFileSync(path.join(dir, 'fonts.css'), 'utf8'), /@font-face/);
    // a NONEMPTY existing shared output is still never touched
    fs.writeFileSync(path.join(dir, 'fonts.css'), '/* shared */');
    await buildFonts(dir, quiet, { addOnly: true });
    assert.match(fs.readFileSync(path.join(dir, 'fonts.css'), 'utf8'), /shared/);
    // an empty ORIGINAL is a missing download (the downloader re-fetches zero-byte files too)
    fs.truncateSync(path.join(dir, 'bender-light.ttf'), 0);
    const broken = await buildFonts(dir, quiet, { addOnly: true });
    assert.ok(broken.errors.some((e) => e.includes('missing font bender-light.ttf')));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('font errors fail the run (runExitCode): a broken font is never a ready deployment', () => {
  assert.equal(runExitCode({ fontErrors: 1 }), 1, 'a font the manifest points at must not silently stay broken');
  assert.equal(runExitCode({}), 0);
  assert.equal(runExitCode({ fontErrors: 0, droppedLeaves: 3 }), 0, 'optional-fallback art keeps the run green');
  assert.equal(runExitCode({ fontErrors: 0, requiredMisses: 1 }), 1, 'unchanged: required misses still win');
});

test('the committed manifest keeps its fonts entry under --add-only (parseArgs stays compatible)', () => {
  assert.equal(parseArgs(['--add-only']).addOnly, true);
  assert.throws(() => parseArgs(['--add-only', '--force']), /never deletes or rewrites/);
  const help = spawnHelp();
  assert.match(help, /--add-only\s+download only files missing on disk/);
  assert.match(help, /missing fonts \/ \.woff2 \/ fonts\.css are still added/);
  assert.match(help, /--download-only\s+plan and download, but never write data\/assets\.json/);
});

function spawnHelp() {
  const r = spawnSync(process.execPath, [path.join(ROOT, 'tools', 'fetch-assets.mjs'), '--help'], { encoding: 'utf8', timeout: 30_000 });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout;
}
